from pathlib import Path
import pandas as pd
import streamlit as st

# Run from the project root:
#   streamlit run dashboard.py
# Expected analytics folder:
#   output/analytics/*.csv

PROJECT_DIR = Path(__file__).resolve().parent
ANALYTICS_DIR = PROJECT_DIR / "output" / "analytics"

FILES = {
    "Accidents by severity": "accidents_by_severity.csv",
    "Accidents by hour": "accidents_by_hour.csv",
    "Accidents by weekday": "accidents_by_weekday.csv",
    "Accidents by weather": "accidents_by_weather.csv",
    "Accidents by city": "accidents_by_city.csv",
    "Road feature presence": "road_feature_presence.csv",
}

st.set_page_config(
    page_title="Road Accident Analytics",
    page_icon="🚦",
    layout="wide",
)

st.title("🚦 Road Accident Analytics Dashboard")
st.caption("A local dashboard powered by the CSV summaries generated by your Airflow pipeline.")

if not ANALYTICS_DIR.exists():
    st.error(f"Analytics folder not found: {ANALYTICS_DIR}")
    st.info("Run your Airflow DAG first and confirm that output/analytics contains the summary CSV files.")
    st.stop()


def load_csv(filename: str):
    path = ANALYTICS_DIR / filename
    if not path.exists():
        return None, f"File not found: {path.name}"
    try:
        frame = pd.read_csv(path)
        if frame.empty:
            return frame, f"{path.name} has no data rows."
        return frame, None
    except Exception as exc:
        return None, f"Could not read {path.name}: {exc}"


def numeric_columns(frame):
    return list(frame.select_dtypes(include="number").columns)


def choose_category_column(frame, numbers):
    # Prefer a non-numeric column; otherwise use the first column.
    categories = [column for column in frame.columns if column not in numbers]
    return categories[0] if categories else frame.columns[0]


def choose_value_column(frame, numbers):
    if not numbers:
        return None
    # Common aggregate column names first.
    preferred = [
        "count", "accidents", "total", "rows", "value", "frequency",
        "number_of_accidents", "accident_count"
    ]
    lower_lookup = {str(column).strip().lower(): column for column in numbers}
    for name in preferred:
        if name in lower_lookup:
            return lower_lookup[name]
    return numbers[-1]


# Load all available summary files.
datasets = {}
warnings = []
for label, filename in FILES.items():
    data, error = load_csv(filename)
    if error:
        warnings.append(f"{label}: {error}")
    elif data is not None:
        datasets[label] = data

if warnings:
    with st.expander("File and data notices", expanded=not datasets):
        for warning in warnings:
            st.warning(warning)

if not datasets:
    st.error("No readable analytics CSV files were found. Check output/analytics and run the Airflow DAG.")
    st.stop()

# Overview metrics use the severity summary when it contains a numeric aggregate.
severity = datasets.get("Accidents by severity")
hourly = datasets.get("Accidents by hour")
weekday = datasets.get("Accidents by weekday")
weather = datasets.get("Accidents by weather")
city = datasets.get("Accidents by city")

metric_cols = st.columns(3)
metric_cols[0].metric("Available summary files", len(datasets))

if severity is not None and numeric_columns(severity):
    sev_value = choose_value_column(severity, numeric_columns(severity))
    metric_cols[1].metric("Severity categories", len(severity))
    metric_cols[2].metric(
        "Total rows in severity summary",
        f"{pd.to_numeric(severity[sev_value], errors='coerce').fillna(0).sum():,.0f}",
    )
else:
    metric_cols[1].metric("Severity categories", "—")
    metric_cols[2].metric("Total in severity summary", "—")

st.divider()
st.subheader("Key summaries")

# Show the first four summaries in a two-column chart layout.
chart_specs = [
    ("Accidents by severity", severity),
    ("Accidents by hour", hourly),
    ("Accidents by weekday", weekday),
    ("Accidents by weather", weather),
]
chart_cols = st.columns(2)

for index, (label, frame) in enumerate(chart_specs):
    with chart_cols[index % 2]:
        st.markdown(f"#### {label}")
        if frame is None:
            st.info("This summary file is not available.")
            continue

        numbers = numeric_columns(frame)
        if not numbers:
            st.dataframe(frame, use_container_width=True, hide_index=True)
            st.caption("No numeric column was detected, so this summary is shown as a table.")
            continue

        category = choose_category_column(frame, numbers)
        value = choose_value_column(frame, numbers)
        plot_frame = frame[[category, value]].copy()
        plot_frame[value] = pd.to_numeric(plot_frame[value], errors="coerce")
        plot_frame = plot_frame.dropna(subset=[value])
        plot_frame[category] = plot_frame[category].astype(str)
        plot_frame = plot_frame.sort_values(value, ascending=False).head(20)
        if not plot_frame.empty:
            st.bar_chart(plot_frame.set_index(category)[value])
        st.caption(f"Chart uses `{category}` and `{value}`.")
        with st.expander("View source table"):
            st.dataframe(frame, use_container_width=True, hide_index=True)

st.divider()
st.subheader("Explore city and road-feature summaries")

explore_cols = st.columns(2)
for col, label in zip(explore_cols, ["Accidents by city", "Road feature presence"]):
    with col:
        st.markdown(f"#### {label}")
        frame = datasets.get(label)
        if frame is None:
            st.info("This summary file is not available.")
            continue
        numbers = numeric_columns(frame)
        if numbers:
            category = choose_category_column(frame, numbers)
            value = choose_value_column(frame, numbers)
            plot_frame = frame[[category, value]].copy()
            plot_frame[value] = pd.to_numeric(plot_frame[value], errors="coerce")
            plot_frame = plot_frame.dropna(subset=[value]).sort_values(value, ascending=False).head(20)
            plot_frame[category] = plot_frame[category].astype(str)
            if not plot_frame.empty:
                st.bar_chart(plot_frame.set_index(category)[value])
            st.caption(f"Chart uses `{category}` and `{value}`.")
        st.dataframe(frame, use_container_width=True, hide_index=True)

st.divider()
st.subheader("Download summary data")
selected_label = st.selectbox("Choose a summary", list(datasets.keys()))
selected_data = datasets[selected_label]
st.download_button(
    label=f"Download {FILES[selected_label]}",
    data=selected_data.to_csv(index=False).encode("utf-8"),
    file_name=FILES[selected_label],
    mime="text/csv",
)

st.caption("Note: charts show the aggregate values present in your CSVs. They do not prove causation.")
